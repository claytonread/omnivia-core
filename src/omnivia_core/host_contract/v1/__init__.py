"""Host Contract v1 (DOC-004 section AA): governed records, codec, and semantics.

This is the stable public surface of the Host Contract v1.0.0 wire contract:
the generated records and closed vocabulary, the codec that enforces the total
result envelope and the trusted-host authority boundary, the compatibility and
migration semantics, Module contribution registration, publication invariants,
and read-only access to the packaged canonical schema and fixtures -- all
re-exported from one place so a caller does not need to know which submodule a
given name lives in. The submodules themselves (:mod:`bound`, :mod:`codec`,
:mod:`compatibility`, :mod:`generated`, :mod:`publication`,
:mod:`registration`, :mod:`resources`) remain importable directly for callers
that prefer explicit provenance.

The governed authority is the exact proposal at commit
``2568f0049256b86fa58dc2387e8302aa4da94ae1``, content-set SHA-256
``31da9251944079ea1bc8db61ed0a393a05e0ce18602f31f6771def4ab243f0ac``, approved
by ``GOV-HOST-CONTRACT-APPROVAL-001`` and incorporated by DOC-004 section AA.
Closure means the public wire semantics are governed and may be implemented; it
does not certify any adapter, conformance host or production build.

Development and conformance controls (``DevelopmentProfile``,
``ShellScenario``, ``TestDriverRequest``/``TestDriverResult``) are represented
here as contracts only. Nothing in this package mounts sources, injects
fixtures or drives a shell.

This surface is additive: the Application Contract v1 (ADR-038) under
:mod:`omnivia_core.contracts.v1` is unchanged and unrelated.

Standard library only. Nothing under ``omnivia_core.host_contract`` may depend
on runtime, storage, HTTP, MCP, CLI, Platform, Dev, or a validation framework.
"""

