def test_a_tls_material_refusal_publishes_no_certificate_path(tmp_path: Path) -> None:
    """`ssl` quotes the file it could not read, and this module must not repeat it.

    A new leak surface this lane introduces: `FileNotFoundError` names the path, and an
    `SSLError` from a mismatched key names it too. `from None` would not be enough --
    it clears `__cause__` and leaves `__context__` referencing the original, one
    attribute access from anything that logs the refusal.
    """
    planted = tmp_path / f"{PLANTED_PATH_FRAGMENT}.pem"
    server = LoopbackHttpServer(
        router=_router(CountingDispatch()),
        principal=PRINCIPAL,
        resolver=_resolver,
        bind=HttpBind(tls=HttpTls(planted, planted)),
    )

    with pytest.raises(HttpTransportError) as caught:
        server.start()

    error = caught.value
    rendered = "".join(
        (
            str(error),
            repr(error.args),
            repr(error.__cause__),
            repr(error.__context__),
            "".join(traceback.format_exception(error)),
        )
    )
    assert PLANTED_PATH_FRAGMENT not in rendered
    assert str(tmp_path) not in rendered
    assert error.__cause__ is None
    assert error.__context__ is None


def test_a_failed_handshake_prints_nothing_and_does_not_stop_the_listener(
    serving: Serving, material: Material, capfd: pytest.CaptureFixture[str]
) -> None:
    """The handshake path is new output surface, and it stays silent.

    `socketserver` prints a traceback from `handle_error` by default, and a handshake
    failure carries the peer's own bytes. Captured at the file-descriptor level because
    the listener answers on its own thread, where `capsys` would see nothing.
    """
    with socket.create_connection((serving.host, serving.port), timeout=20) as client:
        client.sendall(b"not a tls record at all: " + PLANTED_PATH_FRAGMENT.encode())
        try:
            client.recv(65536)
        except OSError:
            pass

    # Still serving, and the successful caller proves the listener survived.
    status, _, _ = _tls_post(
        _client(material),
        serving.host,
        serving.port,
        PROBE_PATH,
        canonical_json_bytes({PROBE_FIELD: PROBE_HEALTH}),
    )
    captured = capfd.readouterr()

    assert status == 200
    assert captured.out == ""
    assert captured.err == ""
    assert PLANTED_PATH_FRAGMENT not in captured.out + captured.err


def test_nothing_this_module_generates_lands_in_the_work_tree(
    material: Material,
) -> None:
    """The stop condition, asserted rather than trusted.

    `.gitignore` covers `*.pem` and `*.key` but not `*.crt`, `*.p12` or `*.pfx`, so a
    stray write with one of those extensions would be committed silently. The rule this
    module follows is stronger than the ignore list: everything goes to pytest's own
    temporary directory and nothing is written under the checkout at all.
    """
    checkout = Path(__file__).resolve().parents[5]
    for path in (
        material.issuing_ca,
        material.certificate_chain,
        material.private_key,
        material.unrelated_key,
    ):
        assert path.is_file()
        assert checkout not in path.resolve().parents
