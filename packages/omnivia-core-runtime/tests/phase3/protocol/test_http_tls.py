"""P2b sub-lane A: the HTTP v1 adapter as a TLS listener.

Hermetic. No hosted environment, no committed certificate, no network beyond this
host's own interfaces. What is pinned here is the capability sub-lane B will point a
real hostname at, and the four refusals that keep it from being a downgrade:

* a non-loopback bind serves **only** with TLS configured, and refuses at construction
  without it -- the merged refusal, unchanged;
* TLS material that cannot be loaded refuses **before a socket exists**, asserted on
  the port rather than on the exception;
* the protocol floor is TLS 1.2 and is stated rather than inherited;
* a cleartext caller is never answered as HTTP by a listener that was asked for TLS.

The last one is the one that has to be observed on the wire. A test that reads the
configuration back proves the configuration; only bytes prove what is served.

Certificate material is generated by the `openssl` CLI into pytest's own temporary
directory, once per session. Nothing is written into the work tree and no dependency
is added for it: if `openssl` is missing this module **fails**, loudly, rather than
skipping -- a skipped test reads exactly like a passing one in a summary line.
"""

